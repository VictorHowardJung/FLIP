function flightData = normalizeFlightTime(flightData)
% Convert source timestamps to seconds relative to the log start.

    if isfield(flightData.metadata, 'timeNormalized') && ...
            flightData.metadata.timeNormalized

        return;

    end

    requiredMetadata = {'logStartTime', 'logEndTime'};

    if ~all(isfield(flightData.metadata, requiredMetadata))

        error('FLIP:MissingTimeMetadata', ...
            'flightData metadata does not contain the log time range.');

    end

    timeOrigin = double(flightData.metadata.logStartTime);
    logEndTimestamp = double(flightData.metadata.logEndTime);

    signalNames = { ...
        'position', ...
        'geographicPosition', ...
        'velocity', ...
        'attitude', ...
        'rates', ...
        'positionSetpoint', ...
        'velocitySetpoint', ...
        'trajectorySetpoint', ...
        'attitudeSetpoint', ...
        'ratesSetpoint', ...
        'vehicleStatus', ...
        'armingState', ...
        'landDetection', ...
        'failureDetector', ...
        'motorCommand', ...
        'actuatorOutput', ...
        'battery', ...
        'estimatorSelector', ...
        'imuDiagnostics', ...
        'imuConsistency', ...
        'estimatorDiagnostics', ...
        'estimatorInnovations', ...
        'estimatorTestRatios', ...
        'gpsDiagnostics', ...
        'controlDemand', ...
        'manualControl', ...
        'rcLink', ...
        'cpuStatus', ...
        'radioStatus', ...
        'telemetryStatus', ...
        'systemPower'};

    for index = 1:numel(signalNames)

        signalName = signalNames{index};

        if isfield(flightData, signalName) && ...
                isfield(flightData.(signalName), 'time')

            flightData.(signalName).timestamp = ...
                flightData.(signalName).time;
            flightData.(signalName).time = ...
                flightData.(signalName).timestamp - timeOrigin;

        end

    end

    if isfield(flightData, 'controlDemand') && ...
            isfield(flightData.controlDemand, 'torqueTime')
        flightData.controlDemand.torqueTimestamp = ...
            flightData.controlDemand.torqueTime;
        flightData.controlDemand.torqueTime = ...
            flightData.controlDemand.torqueTimestamp - timeOrigin;
    end

    if isfield(flightData, 'catalog') && istable(flightData.catalog)

        flightData.catalog.StartTimestamp = flightData.catalog.StartTime;
        flightData.catalog.EndTimestamp = flightData.catalog.EndTime;
        flightData.catalog.StartTime = ...
            flightData.catalog.StartTimestamp - timeOrigin;
        flightData.catalog.EndTime = ...
            flightData.catalog.EndTimestamp - timeOrigin;

    end

    flightData.metadata.logStartTimestamp = timeOrigin;
    flightData.metadata.logEndTimestamp = logEndTimestamp;
    flightData.metadata.logStartTime = 0;
    flightData.metadata.logEndTime = logEndTimestamp - timeOrigin;
    flightData.metadata.duration = logEndTimestamp - timeOrigin;

    flightData.metadata.dropoutTimestamps = ...
        flightData.metadata.dropoutIntervals;
    flightData.metadata.dropoutIntervals = ...
        flightData.metadata.dropoutTimestamps - timeOrigin;

    if ~isfield(flightData.metadata, 'timeReference')
        flightData.metadata.timeReference = 'ULog start';
    end
    if ~isfield(flightData.metadata, 'timestampReference')
        flightData.metadata.timestampReference = 'PX4 system start';
    end
    flightData.metadata.timeNormalized = true;

end
