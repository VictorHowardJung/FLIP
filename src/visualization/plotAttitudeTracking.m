function figureHandle = plotAttitudeTracking(flightData, visibility)
% Compare logged and reference roll, pitch, and yaw.

    if nargin < 2

        visibility = 'on';

    end

    figureHandle = plotThreeAxisTracking( ...
        flightData.attitude, ...
        flightData.attitudeSetpoint, ...
        {'roll', 'pitch', 'yaw'}, ...
        {'roll', 'pitch', 'yaw'}, ...
        {'Roll', 'Pitch', 'Yaw'}, ...
        'Attitude Tracking', ...
        'deg', 180 / pi, visibility);
    decorateFlightTimeAxes( ...
        findall(figureHandle, 'Type', 'axes'), flightData);

end
