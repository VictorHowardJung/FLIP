function figureHandle = plotGPSDiagnostics(flightData, visibility)
% Plot PX4 GPS fix, satellite count, accuracy, DOP, noise, and jamming evidence.

    if nargin < 2, visibility = 'on'; end
    figureHandle = figure('Name', 'GPS Quality and Interference', ...
        'NumberTitle', 'off', 'Color', 'white', ...
        'Position', [85 50 1240 860], 'Visible', visibility);

    if ~available(flightData)
        ax = axes(figureHandle); axis(ax, 'off');
        text(ax, 0.5, 0.5, ...
            'vehicle_gps_position is not available in this log.', ...
            'HorizontalAlignment', 'center', 'FontSize', 12);
        return;
    end

    gps = flightData.gpsDiagnostics;
    t = gps.time(:);
    layout = tiledlayout(figureHandle, 3, 2, ...
        'TileSpacing', 'compact', 'Padding', 'compact');
    title(layout, {'GPS Quality and Interference', ...
        sprintf(['Source: vehicle_gps_position instance %g; enum fields ' ...
        'remain raw to avoid firmware-version guessing'], gps.instanceID)}, ...
        'Interpreter', 'none', 'Color', [0.10 0.10 0.10]);
    ax = gobjects(6, 1);

    ax(1) = nexttile(layout); style(ax(1), 'gpsFixAxes');
    yyaxis(ax(1), 'left');
    stairs(ax(1), t, value(gps, 'fixType'), 'LineWidth', 1.2, ...
        'DisplayName', 'Fix type (raw)', 'Tag', 'gpsFixType');
    ylabel(ax(1), 'Fix type code');
    yyaxis(ax(1), 'right');
    stairs(ax(1), t, value(gps, 'satellitesUsed'), 'LineWidth', 1.2, ...
        'DisplayName', 'Satellites used', 'Tag', 'gpsSatellites');
    ylabel(ax(1), 'Satellites'); title(ax(1), 'Fix and Satellite Count');

    ax(2) = nexttile(layout); style(ax(2), 'gpsAccuracyAxes');
    hold(ax(2), 'on');
    plot(ax(2), t, value(gps, 'eph'), 'LineWidth', 1.2, ...
        'DisplayName', 'EPH', 'Tag', 'gpsEPH');
    plot(ax(2), t, value(gps, 'epv'), 'LineWidth', 1.2, ...
        'DisplayName', 'EPV', 'Tag', 'gpsEPV');
    ylabel(ax(2), 'Estimated accuracy (m)');
    title(ax(2), 'Horizontal and Vertical Position Accuracy');
    legend(ax(2), 'Location', 'best');

    ax(3) = nexttile(layout); style(ax(3), 'gpsDopAxes'); hold(ax(3), 'on');
    plot(ax(3), t, value(gps, 'hdop'), 'LineWidth', 1.2, ...
        'DisplayName', 'HDOP', 'Tag', 'gpsHDOP');
    plot(ax(3), t, value(gps, 'vdop'), 'LineWidth', 1.2, ...
        'DisplayName', 'VDOP', 'Tag', 'gpsVDOP');
    ylabel(ax(3), 'DOP'); title(ax(3), 'Dilution of Precision');
    legend(ax(3), 'Location', 'best');

    ax(4) = nexttile(layout); style(ax(4), 'gpsNoiseAxes');
    yyaxis(ax(4), 'left');
    plot(ax(4), t, value(gps, 'noisePerMs'), 'LineWidth', 1.2, ...
        'DisplayName', 'Noise per ms', 'Tag', 'gpsNoise');
    ylabel(ax(4), 'Noise per ms (raw)');
    yyaxis(ax(4), 'right');
    plot(ax(4), t, value(gps, 'jammingIndicator'), 'LineWidth', 1.2, ...
        'DisplayName', 'Jamming indicator', 'Tag', 'gpsJammingIndicator');
    ylabel(ax(4), 'Jamming indicator (raw)');
    title(ax(4), 'Receiver Noise and Jamming Indicator');

    ax(5) = nexttile(layout); style(ax(5), 'gpsVelocityAxes');
    yyaxis(ax(5), 'left');
    plot(ax(5), t, value(gps, 'velocity'), 'LineWidth', 1.2, ...
        'DisplayName', 'Ground speed', 'Tag', 'gpsVelocity');
    ylabel(ax(5), 'Speed (m/s)');
    yyaxis(ax(5), 'right');
    plot(ax(5), t, value(gps, 'speedAccuracy'), 'LineWidth', 1.2, ...
        'DisplayName', 's_variance_m_s', 'Tag', 'gpsSpeedAccuracy');
    ylabel(ax(5), 'Logged speed uncertainty (m/s)');
    title(ax(5), 'GPS Speed and Logged Uncertainty');

    ax(6) = nexttile(layout); style(ax(6), 'gpsStateAxes'); hold(ax(6), 'on');
    stairs(ax(6), t, value(gps, 'jammingState'), 'LineWidth', 1.2, ...
        'DisplayName', 'Jamming state (raw)', 'Tag', 'gpsJammingState');
    stairs(ax(6), t, value(gps, 'spoofingState'), 'LineWidth', 1.2, ...
        'DisplayName', 'Spoofing state (raw)', 'Tag', 'gpsSpoofingState');
    ylabel(ax(6), 'Raw enum code'); title(ax(6), 'Interference State Codes');
    legend(ax(6), 'Location', 'best');

    for index = 1:numel(ax)
        xlabel(ax(index), 'Time from log start (s)');
        if numel(ax(index).YAxis) > 1, yyaxis(ax(index), 'left'); end
    end
    linkaxes(ax, 'x'); setFullTimeLimits(ax(1), flightData);
    decorateFlightTimeAxes(ax, flightData);
    for index = 1:numel(ax), ax(index).Title.Color = [0.10 0.10 0.10]; end
    attachFigureProvenance(figureHandle, { ...
        'Fix and satellites', 'vehicle_gps_position', ...
        'fix_type, satellites_used', gps.instanceID, 'enum; count', ...
        'none', 'Direct', 'Raw enum retained; row count checked'; ...
        'Position accuracy', 'vehicle_gps_position', 'eph, epv', ...
        gps.instanceID, 'm', 'none', 'Direct', 'Official PX4 field units'; ...
        'DOP', 'vehicle_gps_position', 'hdop, vdop', gps.instanceID, ...
        'ratio', 'none', 'Direct', 'No threshold interpretation applied'; ...
        'Noise and jamming', 'vehicle_gps_position', ...
        'noise_per_ms, jamming_indicator', gps.instanceID, 'raw', ...
        'none', 'Direct', 'Raw receiver values; no rescaling'; ...
        'Speed and uncertainty', 'vehicle_gps_position', ...
        'vel_m_s, s_variance_m_s', gps.instanceID, 'm/s', ...
        'none', 'Direct', 'Field names and row count checked'; ...
        'Interference states', 'vehicle_gps_position', ...
        'jamming_state, spoofing_state', gps.instanceID, 'enum', ...
        'none', 'Direct', 'Raw enum retained for firmware compatibility'});

end

function result = available(data)
    result = isfield(data, 'gpsDiagnostics') && ...
        isfield(data.gpsDiagnostics, 'available') && ...
        data.gpsDiagnostics.available;
end
function y = value(signal, name)
    y = nan(numel(signal.time), 1);
    if isfield(signal, name) && numel(signal.(name)) == numel(signal.time)
        y = double(signal.(name)(:));
    end
end
function style(ax, tag)
    set(ax, 'Tag', tag, 'Color', 'white', ...
        'XColor', [0.15 0.15 0.15], 'YColor', [0.15 0.15 0.15], ...
        'GridColor', [0.70 0.70 0.70], 'GridAlpha', 0.4);
    hold(ax, 'on'); grid(ax, 'on'); box(ax, 'on');
end
function setFullTimeLimits(ax, data)
    if isfield(data, 'metadata') && isfield(data.metadata, 'duration') && ...
            isfinite(data.metadata.duration) && data.metadata.duration > 0
        xlim(ax, [0 data.metadata.duration]);
    end
end
