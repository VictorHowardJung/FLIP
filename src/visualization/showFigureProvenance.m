function provenanceFigure = showFigureProvenance(sourceFigure)
% Display the source data and transformations used by a selected FLIP figure.

    if nargin < 1 || ~isgraphics(sourceFigure, 'figure') || ...
            ~isappdata(sourceFigure, 'FLIPDataProvenance')
        error('FLIP:MissingFigureProvenance', ...
            'This figure does not contain FLIP data-provenance metadata.');
    end

    provenance = getappdata(sourceFigure, 'FLIPDataProvenance');
    provenanceFigure = uifigure( ...
        'Name', ['Data Provenance - ' sourceFigure.Name], ...
        'Position', [120 120 1280 430]);
    grid = uigridlayout(provenanceFigure, [2 1]);
    grid.RowHeight = {42, '1x'};
    uilabel(grid, ...
        'Text', ['Direct = copied from ULog; Converted = unit/offset only; ' ...
        'Derived = calculated by FLIP. Validation describes what was checked.'], ...
        'FontWeight', 'bold', ...
        'WordWrap', 'on');
    uitable(grid, 'Data', provenance, ...
        'ColumnSortable', true, ...
        'ColumnRearrangeable', true);

end
