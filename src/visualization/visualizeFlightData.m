function figureHandles = visualizeFlightData(flightData, visibility, options)
% Create the core Flight Review-style plots and trajectory views.

    arguments
        flightData (1, 1) struct
        visibility (1, 1) string {mustBeMember(visibility, ["on", "off"])} = "on"
        options.ProgressFcn (1, 1) function_handle = @(varargin) []
    end

    plotters = { ...
        'position', @plotPositionTracking, 'Position tracking'; ...
        'velocity', @plotVelocityTracking, 'Velocity tracking'; ...
        'attitude', @plotAttitudeTracking, 'Attitude tracking'; ...
        'rates', @plotRateTracking, 'Angular-rate tracking'; ...
        'motors', @plotMotorCommandVsOutput, 'Motor commands and outputs'; ...
        'battery', @plotBatteryPowerHealth, 'Battery power and health'; ...
        'vibration', @plotIMUVibrationDiagnostics, 'IMU vibration'; ...
        'estimator', @plotEstimatorDiagnostics, 'Estimator diagnostics'; ...
        'gps', @plotGPSDiagnostics, 'GPS diagnostics'; ...
        'controlDemand', @plotControlDemand, 'Control demand'; ...
        'pilotResponse', @plotPilotInputResponse, 'Pilot response'; ...
        'systemHealth', @plotSystemLinkHealth, 'System and link health'; ...
        'trajectory', @plot3DTrajectory, 'Flight trajectory'};
    figureHandles = struct();
    total = size(plotters, 1);
    for index = 1:total
        options.ProgressFcn("plots", index - 1, total, plotters{index, 3});
        plotter = plotters{index, 2};
        figureHandles.(plotters{index, 1}) = plotter(flightData, visibility);
        options.ProgressFcn("plots", index, total, plotters{index, 3});
    end

end
