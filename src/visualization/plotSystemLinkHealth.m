function figureHandle = plotSystemLinkHealth(flightData, visibility)
% Plot CPU, RC, telemetry, radio, power rails, and system/link warning evidence.

    if nargin < 2, visibility = 'on'; end
    figureHandle = figure('Name', 'System and Link Health', ...
        'NumberTitle', 'off', 'Color', 'white', ...
        'Position', [80 45 1280 880], 'Visible', visibility);
    layout = tiledlayout(figureHandle, 3, 2, ...
        'TileSpacing', 'compact', 'Padding', 'compact');
    title(layout, {'System and Communication Health', ...
        ['Raw link/status values are preserved; percentage conversion is ' ...
        'applied only to documented 0-to-1 CPU and RAM fractions.']}, ...
        'Interpreter', 'none', 'Color', [0.10 0.10 0.10]);
    ax = gobjects(6, 1);

    cpu = signal(flightData, 'cpuStatus');
    ax(1) = nexttile(layout); style(ax(1), 'systemCpuAxes'); hold(ax(1), 'on');
    plot(ax(1), cpu.time, 100 .* value(cpu, 'load'), 'LineWidth', 1.2, ...
        'DisplayName', 'CPU load', 'Tag', 'systemCpuLoad');
    plot(ax(1), cpu.time, 100 .* value(cpu, 'ramUsage'), 'LineWidth', 1.2, ...
        'DisplayName', 'RAM usage', 'Tag', 'systemRamUsage');
    ylabel(ax(1), 'Usage (%)'); title(ax(1), 'Autopilot Resource Usage');
    legend(ax(1), 'Location', 'best');

    rc = signal(flightData, 'rcLink');
    ax(2) = nexttile(layout); style(ax(2), 'systemRcAxes');
    yyaxis(ax(2), 'left');
    plot(ax(2), rc.time, value(rc, 'rssi'), 'LineWidth', 1.2, ...
        'DisplayName', 'RSSI', 'Tag', 'systemRcRssi');
    ylabel(ax(2), 'RSSI (raw)');
    yyaxis(ax(2), 'right');
    plot(ax(2), rc.time, value(rc, 'linkQuality'), 'LineWidth', 1.2, ...
        'DisplayName', 'Link quality', 'Tag', 'systemRcLinkQuality');
    ylabel(ax(2), 'Link quality (raw)'); title(ax(2), 'RC Link Quality');

    telemetry = signal(flightData, 'telemetryStatus');
    ax(3) = nexttile(layout); style(ax(3), 'systemTelemetryRateAxes');
    hold(ax(3), 'on');
    plot(ax(3), telemetry.time, value(telemetry, 'txRateAverage'), ...
        'LineWidth', 1.2, 'DisplayName', 'TX rate', ...
        'Tag', 'systemTelemetryTxRate');
    plot(ax(3), telemetry.time, value(telemetry, 'rxRateAverage'), ...
        'LineWidth', 1.2, 'DisplayName', 'RX rate', ...
        'Tag', 'systemTelemetryRxRate');
    ylabel(ax(3), 'Rate (B/s)'); title(ax(3), 'MAVLink Data Rates');
    legend(ax(3), 'Location', 'best');

    radio = signal(flightData, 'radioStatus');
    ax(4) = nexttile(layout); style(ax(4), 'systemRadioAxes'); hold(ax(4), 'on');
    plot(ax(4), radio.time, value(radio, 'rssi'), 'LineWidth', 1.1, ...
        'DisplayName', 'Local RSSI', 'Tag', 'systemRadioRssi');
    plot(ax(4), radio.time, value(radio, 'remoteRssi'), 'LineWidth', 1.1, ...
        'DisplayName', 'Remote RSSI', 'Tag', 'systemRadioRemoteRssi');
    plot(ax(4), radio.time, value(radio, 'noise'), '--', 'LineWidth', 1.0, ...
        'DisplayName', 'Local noise', 'Tag', 'systemRadioNoise');
    plot(ax(4), radio.time, value(radio, 'remoteNoise'), '--', ...
        'LineWidth', 1.0, 'DisplayName', 'Remote noise', ...
        'Tag', 'systemRadioRemoteNoise');
    ylabel(ax(4), 'Radio status value (raw)');
    title(ax(4), 'Telemetry Radio Signal and Noise');
    legend(ax(4), 'Location', 'best');

    power = signal(flightData, 'systemPower');
    ax(5) = nexttile(layout); style(ax(5), 'systemPowerAxes'); hold(ax(5), 'on');
    plot(ax(5), power.time, value(power, 'voltage5V'), 'LineWidth', 1.2, ...
        'DisplayName', '5 V rail', 'Tag', 'systemVoltage5V');
    sensorRails = matrix(power, 'sensor3V3');
    for column = 1:size(sensorRails, 2)
        plot(ax(5), power.time, sensorRails(:, column), '--', ...
            'LineWidth', 0.95, ...
            'DisplayName', sprintf('3.3 V sensor rail %d', column), ...
            'Tag', sprintf('systemVoltage3V3_%d', column));
    end
    ylabel(ax(5), 'Voltage (V)'); title(ax(5), 'Autopilot Power Rails');
    legend(ax(5), 'Location', 'best');

    ax(6) = nexttile(layout); style(ax(6), 'systemEventAxes'); hold(ax(6), 'on');
    stairs(ax(6), rc.time, flagLevel(rc, 'lost', 1), 'LineWidth', 1.1, ...
        'DisplayName', 'RC lost', 'Tag', 'systemRcLost');
    stairs(ax(6), rc.time, flagLevel(rc, 'failsafe', 2), 'LineWidth', 1.1, ...
        'DisplayName', 'RC failsafe', 'Tag', 'systemRcFailsafe');
    stairs(ax(6), power.time, flagLevel(power, ...
        'peripheralOverCurrent', 3), 'LineWidth', 1.1, ...
        'DisplayName', 'Peripheral over-current', ...
        'Tag', 'systemPeripheralOverCurrent');
    stairs(ax(6), power.time, flagLevel(power, ...
        'highPowerOverCurrent', 4), 'LineWidth', 1.1, ...
        'DisplayName', 'High-power over-current', ...
        'Tag', 'systemHighPowerOverCurrent');
    addDropoutMarkers(ax(6), flightData);
    ylim(ax(6), [-0.25 5.5]); yticks(ax(6), 0:5);
    yticklabels(ax(6), {'Normal', 'RC lost', 'RC failsafe', ...
        'Peripheral OC', 'High-power OC', 'Log dropout'});
    title(ax(6), 'Discrete Link, Power, and Logging Events');
    ylabel(ax(6), 'Event level'); legend(ax(6), 'Location', 'best');

    for index = 1:numel(ax)
        xlabel(ax(index), 'Time from log start (s)');
        if numel(ax(index).YAxis) > 1, yyaxis(ax(index), 'left'); end
    end
    linkaxes(ax, 'x'); setFullTimeLimits(ax(1), flightData);
    decorateFlightTimeAxes(ax, flightData);
    for index = 1:numel(ax), ax(index).Title.Color = [0.10 0.10 0.10]; end
    attachFigureProvenance(figureHandle, { ...
        'CPU and RAM', 'cpuload', 'load, ram_usage', cpu.instanceID, ...
        '%', 'multiply logged fraction by 100', 'Converted', ...
        'Synthetic scale test; source rows match time'; ...
        'RC quality/events', 'input_rc', ...
        'rssi, link_quality, rc_lost, rc_failsafe', rc.instanceID, ...
        'raw; bool', 'none', 'Direct', 'Raw values and flags retained'; ...
        'Telemetry rates', 'telemetry_status', ...
        'tx_rate_avg, rx_rate_avg', telemetry.instanceID, 'B/s', ...
        'none', 'Direct', 'Selected instance stated; no aggregation'; ...
        'Radio quality', 'radio_status', ...
        'rssi, remote_rssi, noise, remote_noise', radio.instanceID, ...
        'raw', 'none', 'Direct', 'No unverified dBm conversion'; ...
        'Power rails', 'system_power', 'voltage5v_v, sensors3v3', ...
        power.instanceID, 'V', 'none', 'Direct', ...
        'Field dimensions and units checked'; ...
        'Log dropouts', 'ulogreader metadata', 'DropoutIntervals', ...
        NaN, 's', 'interval drawn at event level 5', 'Direct', ...
        'MATLAB ULog reader metadata; normalized by log origin'});

end

function s = signal(data, name)
    s = struct('available', false, 'time', zeros(0, 1), 'instanceID', NaN);
    if isfield(data, name), s = data.(name); end
end
function output = value(s, name)
    output = nan(numel(s.time), 1);
    if isfield(s, name) && numel(s.(name)) == numel(s.time)
        output = double(s.(name)(:));
    end
end
function output = matrix(s, name)
    output = nan(numel(s.time), 0);
    if isfield(s, name) && size(s.(name), 1) == numel(s.time)
        output = double(s.(name));
    end
end
function output = flagLevel(s, name, level)
    raw = value(s, name); output = zeros(size(raw));
    output(~isfinite(raw)) = NaN; output(isfinite(raw) & raw ~= 0) = level;
end
function addDropoutMarkers(ax, data)
    if ~isfield(data, 'metadata') || ...
            ~isfield(data.metadata, 'dropoutIntervals'), return; end
    intervals = double(data.metadata.dropoutIntervals);
    if size(intervals, 2) ~= 2, return; end
    for index = 1:size(intervals, 1)
        plot(ax, intervals(index, :), [5 5], 'LineWidth', 4, ...
            'Color', [0.75 0.10 0.10], ...
            'DisplayName', firstLabel(index, 'ULog dropout'), ...
            'Tag', 'systemLogDropout');
    end
end
function label = firstLabel(index, textValue)
    label = ''; if index == 1, label = textValue; end
end
function style(ax, tag)
    set(ax, 'Tag', tag, 'Color', 'white', ...
        'XColor', [0.15 0.15 0.15], 'YColor', [0.15 0.15 0.15], ...
        'GridColor', [0.70 0.70 0.70], 'GridAlpha', 0.4);
    hold(ax, 'on'); grid(ax, 'on'); box(ax, 'on');
end
function setFullTimeLimits(ax, data)
    if isfield(data, 'metadata') && isfield(data.metadata, 'duration') && ...
            isfinite(data.metadata.duration) && data.metadata.duration > 0
        xlim(ax, [0 data.metadata.duration]);
    end
end
