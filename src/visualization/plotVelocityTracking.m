function figureHandle = plotVelocityTracking(flightData, visibility)
% Compare logged velocity and references in the PX4 NED frame.

    if nargin < 2

        visibility = 'on';

    end

    figureHandle = plotThreeAxisTracking( ...
        flightData.velocity, ...
        flightData.velocitySetpoint, ...
        {'vx', 'vy', 'vz'}, ...
        {'vx', 'vy', 'vz'}, ...
        {'North vx', 'East vy', 'Down vz'}, ...
        'Local Velocity Tracking (NED)', ...
        'm/s', 1, visibility);
    decorateFlightTimeAxes( ...
        findall(figureHandle, 'Type', 'axes'), flightData);

end
