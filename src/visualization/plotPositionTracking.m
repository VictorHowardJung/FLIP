function figureHandle = plotPositionTracking(flightData, visibility)
% Compare logged position and references in the PX4 NED frame.

    if nargin < 2

        visibility = 'on';

    end

    figureHandle = plotThreeAxisTracking( ...
        flightData.position, ...
        flightData.positionSetpoint, ...
        {'x', 'y', 'z'}, ...
        {'x', 'y', 'z'}, ...
        {'North x', 'East y', 'Down z'}, ...
        'Local Position Tracking (NED)', ...
        'm', 1, visibility);
    decorateFlightTimeAxes( ...
        findall(figureHandle, 'Type', 'axes'), flightData);

end
