function output = formatValue(value, unit)

    if ~isfinite(value)

        output = 'N/A';
        return;

    end

    unit = char(unit);

    if isempty(unit)

        output = sprintf('%.6g', value);

    else

        output = sprintf('%.6g %s', value, unit);

    end

end


function output = availabilityText(available)

    if available

        output = 'Yes';

    else

        output = 'No';

    end

end


function output = statusText(applicability, warningValue)

    output = char(applicability);
    warningValue = char(warningValue);

    if ~isempty(warningValue)

        output = sprintf('%s | %s', output, warningValue);

    end

end


function output = warningText(warningValue)

    output = char(warningValue);

    if isempty(output)

        output = '-';

    end

end


function validateAnalysisResult(analysisResult)

    requiredFields = {'summary', 'spatialSummary'};

    if ~isstruct(analysisResult) || ...
            ~all(isfield(analysisResult, requiredFields)) || ...
            ~istable(analysisResult.summary) || ...
            ~istable(analysisResult.spatialSummary)

        error('FLIP:InvalidAnalysisResult', ...
            'A complete tracking analysis result is required.');

    end

end
