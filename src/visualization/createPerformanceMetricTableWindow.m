function figureHandle = createPerformanceMetricTableWindow( ...
        analysisResult, visibility)
% Display tracking and interval-response metrics with their definitions.

    validateAnalysisResult(analysisResult);

    figureHandle = figure( ...
        'Name', 'FLIP Performance Metric Results', ...
        'NumberTitle', 'off', ...
        'Color', 'white', ...
        'MenuBar', 'none', ...
        'ToolBar', 'none', ...
        'Position', [80, 80, 1440, 720], ...
        'Visible', visibility);
    if isprop(figureHandle, 'Theme')
        figureHandle.Theme = 'light';
    end
    if string(visibility) == "on"
        figureHandle.WindowState = 'maximized';
    end
    tabGroup = uitabgroup(figureHandle, ...
        'Units', 'normalized', ...
        'Position', [0, 0, 1, 1]);

    axisTab = uitab(tabGroup, 'Title', 'Axis Metrics');
    spatialTab = uitab(tabGroup, 'Title', 'Spatial & Orientation');
    guideTab = uitab(tabGroup, 'Title', 'Metric Guide');

    createResultTable(axisTab, axisTableData(analysisResult.summary), ...
        axisColumnNames(), 'axisMetricTable');
    createResultTable(spatialTab, ...
        spatialTableData(analysisResult.spatialSummary), ...
        spatialColumnNames(), 'spatialMetricTable');
    createResultTable(guideTab, metricGuideData(), ...
        {'Metric', 'Meaning', 'How to read it'}, 'metricGuideTable');

    if isfield(analysisResult, 'controlResponse')
        response = analysisResult.controlResponse;
        trackingOnly = isfield(response, 'responseMode') && response.responseMode == "selected";
        if trackingOnly
            responseTab = uitab(tabGroup, 'Title', 'Interval Tracking');
            tag = 'intervalTrackingTable';
            createResultTable(responseTab, trackingTableData(response.summary), ...
                {'Signal', 'Axis', 'RMSE', 'MAE', 'Bias (y-r)', 'Max abs.', ...
                'Std. dev.', 'P95 abs.', 'Tail mean (r-y)', 'Status'}, tag);
            guide = sprintf([ ...
                'Time-weighted tracking errors over the selected interval.\n' ...
                'Tail mean uses paired data in the final 20%% of the observed window. Integral metrics and valid duration are in Axis Metrics.']);
        else
            responseTab = uitab(tabGroup, 'Title', 'Control Response');
            tag = 'controlResponseTable';
            createResultTable(responseTab, responseTableData(response.summary), ...
                {'Signal', 'Axis', 'Response start', 'Interval RMSE', 'Interval MAE', ...
                'Rise 10-90%', 'Settling time', 'Overshoot', 'Steady / tail error (r-y)', ...
                'Status'}, tag);
            guide = sprintf([ ...
                'Detected command steps | Rise: 10-90%% | Settling: +/-%.0f%% | Steady tail: last 20%%\n' ...
                '~ marks a finite-log estimate. Error = target - actual. Step times use the detected command onset.'], ...
                100 * response.settlingThreshold);
        end
        resultTable = findobj(responseTab, 'Tag', tag);
        resultTable.Position = [0.01 0.02 0.98 0.87];
        uicontrol(responseTab, 'Style', 'text', 'Units', 'normalized', ...
            'Position', [0.015 0.90 0.97 0.075], 'BackgroundColor', 'white', ...
            'ForegroundColor', [0.08 0.12 0.18], 'FontName', 'Segoe UI', ...
            'FontSize', 12, 'HorizontalAlignment', 'left', ...
            'String', guide, 'Tag', 'controlResponseGuide');
        setappdata(figureHandle, 'FLIPControlResponse', response);
        tabGroup.SelectedTab = responseTab;
    end

end


function createResultTable(parent, data, columnNames, tag)

    tableHandle = uitable(parent, ...
        'Data', data, ...
        'ColumnName', columnNames, ...
        'RowName', [], ...
        'Units', 'normalized', ...
        'Position', [0.01, 0.02, 0.98, 0.96], ...
        'FontName', 'Segoe UI', ...
        'FontSize', 12, ...
        'ForegroundColor', [0.08 0.12 0.18], ...
        'BackgroundColor', [1 1 1; 0.94 0.96 0.99], ...
        'Tag', tag);
    switch tag
        case 'axisMetricTable'
            tableHandle.ColumnWidth = {110, 70, 85, 120, 110, 110, 110, ...
                110, 110, 140, 140, 140, 85, 85, 110, 260};
        case 'spatialMetricTable'
            tableHandle.ColumnWidth = {170, 85, 110, 110, 110, 110, ...
                140, 140, 85, 85, 110, 120, 260};
        case 'metricGuideTable'
            tableHandle.ColumnWidth = {120, 440, 900};
        case 'controlResponseTable'
            tableHandle.ColumnWidth = {100, 65, 105, 110, 110, 105, 110, 95, 190, 400};
        case 'intervalTrackingTable'
            tableHandle.ColumnWidth = {100, 65, 100, 100, 100, 100, 100, 100, 160, 420};
    end

end


function data = trackingTableData(summary)
    data = cell(height(summary), 10);
    for row = 1:height(summary)
        unit = summary.ValueUnit(row);
        data(row, :) = {char(summary.Signal(row)), char(summary.Axis(row)), ...
            formatValue(summary.IntervalRMSE(row), unit), ...
            formatValue(summary.IntervalMAE(row), unit), ...
            formatValue(summary.IntervalBias(row), unit), ...
            formatValue(summary.IntervalMaxAbsError(row), unit), ...
            formatValue(summary.IntervalStdDev(row), unit), ...
            formatValue(summary.IntervalP95AbsError(row), unit), ...
            formatValue(summary.TailMeanError(row), unit), char(summary.Status(row))};
    end
end

function data = responseTableData(summary)
    data = cell(height(summary), 10);
    for row = 1:height(summary)
        error = summary.SteadyStateError(row);
        if ~isfinite(error)
            error = summary.TailMeanError(row);
        end
        start = summary.ResponseStart(row);
        if ~isfinite(start)
            start = summary.WindowStart(row);
        end
        data(row, :) = {char(summary.Signal(row)), char(summary.Axis(row)), ...
            formatValue(start, 's'), ...
            formatValue(summary.IntervalRMSE(row), summary.ValueUnit(row)), ...
            formatValue(summary.IntervalMAE(row), summary.ValueUnit(row)), ...
            responseValue(summary.RiseTime(row), 's', summary.FinalValueEstimated(row)), ...
            responseValue(summary.SettlingTime(row), 's', summary.FinalValueEstimated(row)), ...
            responseValue(summary.Overshoot(row), '%', summary.FinalValueEstimated(row)), ...
            responseValue(error, summary.ValueUnit(row), ~summary.SteadyStateAvailable(row)), ...
            char(summary.Status(row))};
    end
end

function textValue = responseValue(value, unit, estimated)
    textValue = formatValue(value, unit);
    if estimated && isfinite(value)
        textValue = ['~' textValue];
    end
end


function data = axisTableData(summary)

    rowCount = height(summary);
    data = cell(rowCount, 16);

    for rowIndex = 1:rowCount

        data{rowIndex, 1} = char(summary.Signal(rowIndex));
        data{rowIndex, 2} = char(summary.Axis(rowIndex));
        data{rowIndex, 3} = availabilityText(summary.Available(rowIndex));
        data{rowIndex, 4} = formatValue( ...
            summary.MeanError(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 5} = formatValue( ...
            summary.MAE(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 6} = formatValue( ...
            summary.RMSE(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 7} = formatValue( ...
            summary.StdDev(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 8} = formatValue( ...
            summary.P95AbsError(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 9} = formatValue( ...
            summary.MaxAbsError(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 10} = formatValue( ...
            summary.IAE(rowIndex), summary.IAEUnit(rowIndex));
        data{rowIndex, 11} = formatValue( ...
            summary.ISE(rowIndex), summary.ISEUnit(rowIndex));
        data{rowIndex, 12} = formatValue( ...
            summary.ITAE(rowIndex), summary.ITAEUnit(rowIndex));
        data{rowIndex, 13} = summary.Samples(rowIndex);
        data{rowIndex, 14} = summary.Segments(rowIndex);
        data{rowIndex, 15} = formatValue( ...
            summary.ValidDuration(rowIndex), 's');
        data{rowIndex, 16} = statusText( ...
            summary.Applicability(rowIndex), summary.Warning(rowIndex));

    end

end


