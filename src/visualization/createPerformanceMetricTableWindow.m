function figureHandle = createPerformanceMetricTableWindow( ...
        analysisResult, visibility)
% Create tabs for axis metrics, spatial metrics, and metric definitions.

    validateAnalysisResult(analysisResult);

    figureHandle = figure( ...
        'Name', 'FLIP Performance Metric Results', ...
        'NumberTitle', 'off', ...
        'Color', 'white', ...
        'MenuBar', 'none', ...
        'ToolBar', 'none', ...
        'Position', [80, 80, 1440, 720], ...
        'Visible', visibility);
    if isprop(figureHandle, 'Theme')
        figureHandle.Theme = 'light';
    end
    if string(visibility) == "on"
        figureHandle.WindowState = 'maximized';
    end
    tabGroup = uitabgroup(figureHandle, ...
        'Units', 'normalized', ...
        'Position', [0, 0, 1, 1]);

    axisTab = uitab(tabGroup, 'Title', 'Axis Metrics');
    spatialTab = uitab(tabGroup, 'Title', 'Spatial & Orientation');
    guideTab = uitab(tabGroup, 'Title', 'Metric Guide');

    createResultTable(axisTab, axisTableData(analysisResult.summary), ...
        axisColumnNames(), 'axisMetricTable');
    createResultTable(spatialTab, ...
        spatialTableData(analysisResult.spatialSummary), ...
        spatialColumnNames(), 'spatialMetricTable');
    createResultTable(guideTab, metricGuideData(), ...
        {'Metric', 'Meaning', 'How to read it'}, 'metricGuideTable');

end


function createResultTable(parent, data, columnNames, tag)

    tableHandle = uitable(parent, ...
        'Data', data, ...
        'ColumnName', columnNames, ...
        'RowName', [], ...
        'Units', 'normalized', ...
        'Position', [0.01, 0.02, 0.98, 0.96], ...
        'FontName', 'Segoe UI', ...
        'FontSize', 12, ...
        'ForegroundColor', [0.08 0.12 0.18], ...
        'BackgroundColor', [1 1 1; 0.94 0.96 0.99], ...
        'Tag', tag);
    switch tag
        case 'axisMetricTable'
            tableHandle.ColumnWidth = {110, 70, 85, 120, 110, 110, 110, ...
                110, 110, 140, 140, 140, 85, 85, 110, 260};
        case 'spatialMetricTable'
            tableHandle.ColumnWidth = {170, 85, 110, 110, 110, 110, ...
                140, 140, 85, 85, 110, 120, 260};
        case 'metricGuideTable'
            tableHandle.ColumnWidth = {120, 440, 900};
    end

end


function data = axisTableData(summary)

    rowCount = height(summary);
    data = cell(rowCount, 16);

    for rowIndex = 1:rowCount

        data{rowIndex, 1} = char(summary.Signal(rowIndex));
        data{rowIndex, 2} = char(summary.Axis(rowIndex));
        data{rowIndex, 3} = availabilityText(summary.Available(rowIndex));
        data{rowIndex, 4} = formatValue( ...
            summary.MeanError(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 5} = formatValue( ...
            summary.MAE(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 6} = formatValue( ...
            summary.RMSE(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 7} = formatValue( ...
            summary.StdDev(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 8} = formatValue( ...
            summary.P95AbsError(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 9} = formatValue( ...
            summary.MaxAbsError(rowIndex), summary.ValueUnit(rowIndex));
        data{rowIndex, 10} = formatValue( ...
            summary.IAE(rowIndex), summary.IAEUnit(rowIndex));
        data{rowIndex, 11} = formatValue( ...
            summary.ISE(rowIndex), summary.ISEUnit(rowIndex));
        data{rowIndex, 12} = formatValue( ...
            summary.ITAE(rowIndex), summary.ITAEUnit(rowIndex));
        data{rowIndex, 13} = summary.Samples(rowIndex);
        data{rowIndex, 14} = summary.Segments(rowIndex);
        data{rowIndex, 15} = formatValue( ...
            summary.ValidDuration(rowIndex), 's');
        data{rowIndex, 16} = statusText( ...
            summary.Applicability(rowIndex), summary.Warning(rowIndex));

    end

end


