function figureHandle = plotRateTracking(flightData, visibility)
% Compare logged and reference body angular rates.

    if nargin < 2

        visibility = 'on';

    end

    figureHandle = plotThreeAxisTracking( ...
        flightData.rates, ...
        flightData.ratesSetpoint, ...
        {'roll', 'pitch', 'yaw'}, ...
        {'roll', 'pitch', 'yaw'}, ...
        {'Roll rate', 'Pitch rate', 'Yaw rate'}, ...
        'Angular Rate Tracking (Body FRD)', ...
        'deg/s', 180 / pi, visibility);
    decorateFlightTimeAxes( ...
        findall(figureHandle, 'Type', 'axes'), flightData);

end
