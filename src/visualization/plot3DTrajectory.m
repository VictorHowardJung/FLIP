function figureHandle = plot3DTrajectory(flightData, visibility)
% Show the logged trajectory in NED coordinates and a North-up top view.

    if nargin < 2

        visibility = 'on';

    end

    viewFrame = createTrajectoryViewFrame(flightData);
    north = viewFrame.north;
    east = viewFrame.east;
    down = viewFrame.down;
    valid = viewFrame.validPosition;
    directionLength = calculateDirectionLength(north(valid), east(valid), down(valid));
    first = viewFrame.startIndex;
    last = viewFrame.endIndex;

    figureHandle = figure( ...
        'Name', 'Flight Trajectory Views', ...
        'NumberTitle', 'off', ...
        'Color', 'white', ...
        'Position', [100 100 1280 720], ...
        'Visible', visibility);

    layout = tiledlayout(figureHandle, 1, 2, ...
        'TileSpacing', 'compact', ...
        'Padding', 'compact');

    trajectoryAxes = nexttile(layout, 1);
    trajectoryAxes.Tag = 'trajectory3D';
    styleAxes(trajectoryAxes);
    disableDefaultInteractivity(trajectoryAxes);
    trajectoryAxes.Interactions = [];
    hold(trajectoryAxes, 'on');

    drawStartAltitudePlane(trajectoryAxes, north, east, viewFrame.originNED(3));

    plot3(trajectoryAxes, north, east, repmat(viewFrame.originNED(3), size(down)), ...
        '--', ...
        'Color', [0.55, 0.58, 0.62], ...
        'LineWidth', 0.9, ...
        'HandleVisibility', 'off');

    plot3(trajectoryAxes, north, east, down, ...
        'Color', [0.10, 0.35, 0.80], ...
        'LineWidth', 1.5, ...
        'DisplayName', 'Flight path');

    scatter3(trajectoryAxes, north(first), east(first), down(first), ...
        60, [0.10, 0.65, 0.20], 'filled', ...
        'DisplayName', 'Start');

    scatter3(trajectoryAxes, north(last), east(last), down(last), ...
        60, [0.85, 0.15, 0.15], 'filled', ...
        'DisplayName', 'End');

    quiver3(trajectoryAxes, north(first), east(first), down(first), ...
        directionLength, 0, 0, 0, ...
        'Color', [0.10, 0.10, 0.10], ...
        'LineWidth', 1.2, ...
        'MaxHeadSize', 0.6, ...
        'DisplayName', 'North');

    xlabel(trajectoryAxes, 'North x (m)');
    ylabel(trajectoryAxes, 'East y (m)');
    zlabel(trajectoryAxes, 'Down z (m)');
    title(trajectoryAxes, { ...
        '3D Trajectory (NED)', ...
        'Logged local-position reference'}, ...
        'Color', [0.10, 0.10, 0.10]);
    finishAxes(trajectoryAxes);
    trajectoryAxes.Projection = 'perspective';
    trajectoryAxes.ZDir = 'reverse';
    view(trajectoryAxes, 25, 28);

    topAxes = nexttile(layout, 2);
    topAxes.Tag = 'trajectoryTop';
    styleAxes(topAxes);
    disableDefaultInteractivity(topAxes);
    topAxes.Interactions = [];
    hold(topAxes, 'on');

    plot(topAxes, east, north, ...
        'Color', [0.10, 0.35, 0.80], ...
        'LineWidth', 1.5, ...
        'DisplayName', 'Flight path');

    scatter(topAxes, east(first), north(first), ...
        60, [0.10, 0.65, 0.20], 'filled', ...
        'DisplayName', 'Start');

    scatter(topAxes, east(last), north(last), ...
        60, [0.85, 0.15, 0.15], 'filled', ...
        'DisplayName', 'End');

    quiver(topAxes, east(first), north(first), 0, directionLength, 0, ...
        'Color', [0.10, 0.10, 0.10], ...
        'LineWidth', 1.2, ...
        'MaxHeadSize', 0.6, ...
        'DisplayName', 'North');

    xlabel(topAxes, 'East y (m)');
    ylabel(topAxes, 'North x (m)');
    title(topAxes, { ...
        'Top View (NED)', ...
        'East right, North up'}, ...
        'Color', [0.10, 0.10, 0.10]);
    finishAxes(topAxes);
    view(topAxes, 2);

end


function drawStartAltitudePlane(axesHandle, north, east, referenceDown)

    valid = isfinite(north) & isfinite(east);
    north = north(valid);
    east = east(valid);

    northSpan = max(north) - min(north);
    eastSpan = max(east) - min(east);
    padding = 0.08 * max([northSpan, eastSpan, 1]);

    northLimits = [min(north) - padding, max(north) + padding];
    eastLimits = [min(east) - padding, max(east) + padding];

    northGrid = linspace(northLimits(1), northLimits(2), 8);
    eastGrid = linspace(eastLimits(1), eastLimits(2), 8);
    [northPlane, eastPlane] = meshgrid(northGrid, eastGrid);

    surface(axesHandle, northPlane, eastPlane, ...
        repmat(referenceDown, size(northPlane)), ...
        'FaceColor', [0.78, 0.86, 0.94], ...
        'FaceAlpha', 0.20, ...
        'EdgeColor', [0.58, 0.65, 0.72], ...
        'EdgeAlpha', 0.28, ...
        'DisplayName', 'Start-altitude plane');

end


function styleAxes(axesHandle)

    set(axesHandle, ...
        'Color', 'white', ...
        'XColor', [0.15, 0.15, 0.15], ...
        'YColor', [0.15, 0.15, 0.15], ...
        'ZColor', [0.15, 0.15, 0.15], ...
        'GridColor', [0.70, 0.70, 0.70], ...
        'GridAlpha', 0.45);

end


function finishAxes(axesHandle)

    grid(axesHandle, 'on');
    box(axesHandle, 'on');
    axis(axesHandle, 'equal');
    axis(axesHandle, 'padded');
    legendHandle = legend(axesHandle, 'Location', 'best');
    set(legendHandle, ...
        'Color', 'white', ...
        'TextColor', [0.10, 0.10, 0.10], ...
        'EdgeColor', [0.45, 0.45, 0.45]);

end


function directionLength = calculateDirectionLength(north, east, down)

    northSpan = max(north) - min(north);
    eastSpan = max(east) - min(east);
    downSpan = max(down) - min(down);
    directionLength = 0.15 * max([northSpan, eastSpan, downSpan, 1]);

end
