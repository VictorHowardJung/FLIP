function figureHandle = plotThreeAxisTracking(actualSignal, setpointSignal, ...
        actualFields, setpointFields, axisLabels, figureName, unit, ...
        scaleFactor, visibility)
% Plot three-axis logged states and references in the Flight Review style.

    if nargin < 9

        visibility = 'on';

    end

    if numel(actualFields) ~= 3 || numel(setpointFields) ~= 3 || ...
            numel(axisLabels) ~= 3

        error('FLIP:InvalidPlotFieldDefinition', ...
            'Three actual fields, setpoint fields, and labels are required.');

    end

    actualColor = [0.85, 0.15, 0.15];
    setpointColor = [0.10, 0.60, 0.20];

    figureHandle = figure( ...
        'Name', figureName, ...
        'NumberTitle', 'off', ...
        'Color', 'white', ...
        'Position', [80 50 1400 900], ...
        'Visible', visibility);

    layout = tiledlayout(figureHandle, 3, 1, ...
        'TileSpacing', 'compact', ...
        'Padding', 'compact');
    layout.Tag = 'FLIPTrackingLayout';

    title(layout, figureName, ...
        'Interpreter', 'none', ...
        'Color', [0.10, 0.10, 0.10]);
    axesHandles = gobjects(3, 1);

    for axisIndex = 1:3

        axesHandles(axisIndex) = nexttile(layout);
        set(axesHandles(axisIndex), ...
            'Color', 'white', ...
            'XColor', [0.15, 0.15, 0.15], ...
            'YColor', [0.15, 0.15, 0.15], ...
            'GridColor', [0.70, 0.70, 0.70], ...
            'GridAlpha', 0.45);
        hold(axesHandles(axisIndex), 'on');

        actualField = actualFields{axisIndex};
        axesHandles(axisIndex).Tag = ['FLIPTrackingAxis_' actualField];
        setpointField = setpointFields{axisIndex};

        if isfield(actualSignal, actualField) && ...
                ~isempty(actualSignal.(actualField))

            plot(axesHandles(axisIndex), actualSignal.time, ...
                scaleFactor .* actualSignal.(actualField), ...
                'Color', actualColor, ...
                'LineWidth', 1.2, ...
                'DisplayName', 'Estimated');

        end

        if isfield(setpointSignal, 'available') && ...
                setpointSignal.available && ...
                isfield(setpointSignal, setpointField) && ...
                ~isempty(setpointSignal.(setpointField))

            plot(axesHandles(axisIndex), setpointSignal.time, ...
                scaleFactor .* setpointSignal.(setpointField), ...
                'Color', setpointColor, ...
                'LineWidth', 1.2, ...
                'DisplayName', 'Setpoint');

        end

        ylabel(axesHandles(axisIndex), ...
            sprintf('%s (%s)', axisLabels{axisIndex}, unit));
        grid(axesHandles(axisIndex), 'on');
        box(axesHandles(axisIndex), 'on');

        plottedLines = findobj(axesHandles(axisIndex), 'Type', 'line');

        if ~isempty(plottedLines)

            legendHandle = legend(axesHandles(axisIndex), ...
                'Location', 'best');
            set(legendHandle, ...
                'Color', 'white', ...
                'TextColor', [0.10, 0.10, 0.10], ...
                'EdgeColor', [0.45, 0.45, 0.45]);

        else

            text(axesHandles(axisIndex), 0.5, 0.5, ...
                'Signal not available', ...
                'Units', 'normalized', ...
                'HorizontalAlignment', 'center');

        end

    end

    xlabel(axesHandles(3), 'Time from log start (s)');
    linkaxes(axesHandles, 'x');

end
