function figureHandle = plotTrackingErrors(analysisResult, visibility)
% Plot synchronized position, velocity, attitude, and angular-rate tracking errors.

    if nargin < 2

        visibility = 'on';

    end

    figureHandle = figure( ...
        'Name', 'Synchronized Tracking Errors', ...
        'NumberTitle', 'off', ...
        'Color', 'white', ...
        'Position', [70 60 1500 850], ...
        'Visible', visibility);

    layout = tiledlayout(figureHandle, 2, 2, ...
        'TileSpacing', 'compact', ...
        'Padding', 'compact');

    title(layout, 'Synchronized Tracking Errors', ...
        'Color', [0.10, 0.10, 0.10]);

    plotErrorGroup(nexttile(layout), analysisResult.position, ...
        {'x', 'y', 'z'}, {'X', 'Y', 'Z'}, 'Position error', 'm');

    plotErrorGroup(nexttile(layout), analysisResult.velocity, ...
        {'x', 'y', 'z'}, {'X', 'Y', 'Z'}, 'Velocity error', 'm/s');

    plotErrorGroup(nexttile(layout), analysisResult.attitude, ...
        {'roll', 'pitch', 'yaw'}, {'Roll', 'Pitch', 'Yaw'}, ...
        'Attitude error', 'deg');

    plotErrorGroup(nexttile(layout), analysisResult.rates, ...
        {'roll', 'pitch', 'yaw'}, {'Roll', 'Pitch', 'Yaw'}, ...
        'Angular-rate error', 'deg/s');

    decorateFlightTimeAxes( ...
        findall(figureHandle, 'Type', 'axes'), analysisResult);

end


function plotErrorGroup(axesHandle, group, fields, labels, plotTitle, unit)

    colors = lines(3);

    set(axesHandle, ...
        'Color', 'white', ...
        'XColor', [0.15, 0.15, 0.15], ...
        'YColor', [0.15, 0.15, 0.15], ...
        'GridColor', [0.70, 0.70, 0.70], ...
        'GridAlpha', 0.45);

    hold(axesHandle, 'on');

    for axisIndex = 1:3

        channel = group.(fields{axisIndex});

        if channel.available

            plot(axesHandle, channel.synchronized.time, ...
                channel.synchronized.error, ...
                'Color', colors(axisIndex, :), ...
                'LineWidth', 1.1, ...
                'DisplayName', labels{axisIndex});

        end

    end

    yline(axesHandle, 0, '--', ...
        'Color', [0.35, 0.35, 0.35], ...
        'HandleVisibility', 'off');

    title(axesHandle, plotTitle, 'Color', [0.10, 0.10, 0.10]);
    xlabel(axesHandle, 'Time from log start (s)');
    ylabel(axesHandle, sprintf('Actual - setpoint (%s)', unit));
    grid(axesHandle, 'on');
    box(axesHandle, 'on');

    plottedLines = findobj(axesHandle, ...
        '-and', 'Type', 'line', '-not', 'HandleVisibility', 'off');

    if ~isempty(plottedLines)

        legendHandle = legend(axesHandle, 'Location', 'best');
        set(legendHandle, ...
            'Color', 'white', ...
            'TextColor', [0.10, 0.10, 0.10], ...
            'EdgeColor', [0.45, 0.45, 0.45]);

    end

end
