function figureHandle = plotPilotInputResponse(flightData, visibility)
% Compare manual inputs with attitude, angular rates, and thrust demand on a common time axis.

    if nargin < 2, visibility = 'on'; end
    figureHandle = figure('Name', 'Pilot Input and Vehicle Response', ...
        'NumberTitle', 'off', 'Color', 'white', ...
        'Position', [95 65 1220 780], 'Visible', visibility);

    if ~isfield(flightData, 'manualControl') || ...
            ~flightData.manualControl.available
        ax = axes(figureHandle); axis(ax, 'off');
        text(ax, 0.5, 0.5, ...
            'manual_control_setpoint is not available in this log.', ...
            'HorizontalAlignment', 'center', 'FontSize', 12);
        return;
    end

    manual = flightData.manualControl;
    valid = logicalMask(manual, 'valid');
    layout = tiledlayout(figureHandle, 2, 2, ...
        'TileSpacing', 'compact', 'Padding', 'compact');
    title(layout, {'Pilot Input and Vehicle Response', ...
        ['Time association only: manual stick input is not treated as an ' ...
        'attitude setpoint in modes that reshape or ignore it.']}, ...
        'Interpreter', 'none', 'Color', [0.10 0.10 0.10]);
    ax = gobjects(4, 1);

    ax(1) = nexttile(layout);
    dualPlot(ax(1), manual.time, masked(manual, 'roll', valid), ...
        flightData.attitude.time, rad2deg(flightData.attitude.roll), ...
        'Roll stick', 'Actual roll', 'Actual angle (deg)', ...
        'pilotRollInput', 'pilotActualRoll');

    ax(2) = nexttile(layout);
    dualPlot(ax(2), manual.time, masked(manual, 'pitch', valid), ...
        flightData.attitude.time, rad2deg(flightData.attitude.pitch), ...
        'Pitch stick', 'Actual pitch', 'Actual angle (deg)', ...
        'pilotPitchInput', 'pilotActualPitch');

    ax(3) = nexttile(layout);
    dualPlot(ax(3), manual.time, masked(manual, 'yaw', valid), ...
        flightData.rates.time, rad2deg(flightData.rates.yaw), ...
        'Yaw stick', 'Actual yaw rate', 'Actual rate (deg/s)', ...
        'pilotYawInput', 'pilotActualYawRate');

    thrustTime = zeros(0, 1); thrustMagnitude = zeros(0, 1);
    if isfield(flightData, 'controlDemand') && ...
            flightData.controlDemand.available
        thrustTime = flightData.controlDemand.time;
        thrust = flightData.controlDemand.thrust;
        thrustMagnitude = sqrt(sum(thrust .^ 2, 2));
        thrustMagnitude(any(~isfinite(thrust), 2)) = NaN;
    end
    ax(4) = nexttile(layout);
    dualPlot(ax(4), manual.time, masked(manual, 'throttle', valid), ...
        thrustTime, thrustMagnitude, 'Throttle input', ...
        'Thrust magnitude', 'Normalized thrust magnitude', ...
        'pilotThrottleInput', 'pilotThrustDemand');

    titles = {'Roll Input and Roll Response', ...
        'Pitch Input and Pitch Response', ...
        'Yaw Input and Yaw-Rate Response', ...
        'Throttle Input and Thrust Demand'};
    for index = 1:numel(ax)
        title(ax(index), titles{index});
        xlabel(ax(index), 'Time from log start (s)');
        yyaxis(ax(index), 'left');
    end
    linkaxes(ax, 'x'); setFullTimeLimits(ax(1), flightData);
    decorateFlightTimeAxes(ax, flightData);
    for index = 1:numel(ax), ax(index).Title.Color = [0.10 0.10 0.10]; end
    attachFigureProvenance(figureHandle, { ...
        'Roll/pitch/yaw/throttle input', 'manual_control_setpoint', ...
        'roll, pitch, yaw, throttle, valid', manual.instanceID, ...
        'normalized', 'invalid samples -> NaN', 'Direct', ...
        'Logged valid flag applied; no rescaling'; ...
        'Actual roll/pitch', 'vehicle_attitude', 'q', ...
        flightData.attitude.instanceID, 'deg', ...
        'Hamilton quaternion -> ZYX Euler -> rad2deg', 'Converted', ...
        'Quaternion convention and synthetic rotations tested'; ...
        'Actual yaw rate', 'vehicle_angular_velocity', 'xyz(:,3)', ...
        flightData.rates.instanceID, 'deg/s', 'rad2deg', 'Converted', ...
        'Direct rate field with unit conversion'; ...
        'Thrust magnitude', 'vehicle_thrust_setpoint', 'xyz', ...
        fieldOrNaN(flightData, 'controlDemand', 'instanceID'), ...
        'normalized', 'sqrt(x^2+y^2+z^2)', 'Derived', ...
        'Synthetic Euclidean-norm test'; ...
        'Input/response relationship', 'multiple', 'independent timestamps', ...
        NaN, 's', 'overlaid without interpolation', 'Association only', ...
        'No causality or tracking-error claim'});

end

function dualPlot(ax, leftTime, leftValue, rightTime, rightValue, ...
        leftLabel, rightLabel, rightUnit, leftTag, rightTag)
    set(ax, 'Color', 'white', 'XColor', [0.15 0.15 0.15], ...
        'GridColor', [0.70 0.70 0.70], 'GridAlpha', 0.4);
    yyaxis(ax, 'left');
    leftLine = plot(ax, leftTime, leftValue, 'LineWidth', 1.2, ...
        'DisplayName', leftLabel, 'Tag', leftTag);
    ylabel(ax, 'Normalized manual input'); ylim(ax, [-1.05 1.05]);
    yyaxis(ax, 'right');
    rightLine = plot(ax, rightTime, rightValue, 'LineWidth', 1.2, ...
        'DisplayName', rightLabel, 'Tag', rightTag);
    ylabel(ax, rightUnit); grid(ax, 'on'); box(ax, 'on');
    legend(ax, [leftLine rightLine], 'Location', 'best');
end
function setFullTimeLimits(ax, data)
    if isfield(data, 'metadata') && isfield(data.metadata, 'duration') && ...
            isfinite(data.metadata.duration) && data.metadata.duration > 0
        xlim(ax, [0 data.metadata.duration]);
    end
end
function result = logicalMask(signal, name)
    result = true(numel(signal.time), 1);
    if isfield(signal, name) && numel(signal.(name)) == numel(signal.time)
        raw = double(signal.(name)(:));
        result = isfinite(raw) & raw ~= 0;
    end
end
function result = masked(signal, name, valid)
    result = nan(numel(signal.time), 1);
    if isfield(signal, name) && numel(signal.(name)) == numel(signal.time)
        result = double(signal.(name)(:)); result(~valid) = NaN;
    end
end
function value = fieldOrNaN(data, structName, fieldName)
    value = NaN;
    if isfield(data, structName) && isfield(data.(structName), fieldName)
        value = data.(structName).(fieldName);
    end
end
