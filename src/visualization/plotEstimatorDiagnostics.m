function figureHandle = plotEstimatorDiagnostics(flightData, visibility)
% Plot PX4 EKF innovations, test ratios, accuracy, resets, and state flags.

    if nargin < 2, visibility = 'on'; end
    figureHandle = figure('Name', 'Estimator Diagnostics', ...
        'NumberTitle', 'off', 'Color', 'white', ...
        'Position', [80 45 1280 880], 'Visible', visibility);

    if ~available(flightData, 'estimatorDiagnostics')
        unavailable(figureHandle, ...
            'estimator_status is not available in this log.');
        return;
    end

    status = flightData.estimatorDiagnostics;
    innovations = signalOrEmpty(flightData, 'estimatorInnovations');
    layout = tiledlayout(figureHandle, 3, 2, ...
        'TileSpacing', 'compact', 'Padding', 'compact');
    title(layout, {'Estimator (EKF) Diagnostics', ...
        sprintf(['Source estimator instance %g selected from ' ...
        'estimator_selector_status; threshold 1 is shown only for test ratios'], ...
        status.instanceID)}, 'Interpreter', 'none', 'Color', [0.10 0.10 0.10]);
    axesHandles = gobjects(6, 1);

    axesHandles(1) = nexttile(layout); style(axesHandles(1), 'ekfRatioAxes');
    hold(axesHandles(1), 'on');
    ratioNames = {'velocityTestRatio', 'positionTestRatio', ...
        'heightTestRatio', 'headingTestRatio'};
    ratioLabels = {'Velocity', 'Position', 'Height', 'Heading'};
    for index = 1:numel(ratioNames)
        plot(axesHandles(1), status.time, vector(status, ...
            ratioNames{index}), 'LineWidth', 1.1, ...
            'DisplayName', ratioLabels{index}, ...
            'Tag', ['ekf' ratioNames{index}]);
    end
    yline(axesHandles(1), 1, '--r', 'Gate ratio = 1', ...
        'HandleVisibility', 'off');
    title(axesHandles(1), 'Estimator Summary Test Ratios');
    ylabel(axesHandles(1), 'Normalized test ratio');
    legend(axesHandles(1), 'Location', 'best');

    axesHandles(2) = nexttile(layout); style(axesHandles(2), 'ekfPosInnovAxes');
    plotInnovationGroup(axesHandles(2), innovations, ...
        {'gpsHorizontalPosition', 'gpsVerticalPosition', ...
        'baroVerticalPosition'}, {'GPS horizontal', 'GPS vertical', 'Baro vertical'}, ...
        'Position/Height Innovations', 'Innovation (m)', 'ekfPosInnov');

    axesHandles(3) = nexttile(layout); style(axesHandles(3), 'ekfVelInnovAxes');
    plotInnovationGroup(axesHandles(3), innovations, ...
        {'gpsHorizontalVelocity', 'gpsVerticalVelocity'}, ...
        {'GPS horizontal', 'GPS vertical'}, ...
        'Velocity Innovations', 'Innovation (m/s)', 'ekfVelInnov');

    axesHandles(4) = nexttile(layout); style(axesHandles(4), 'ekfAccuracyAxes');
    hold(axesHandles(4), 'on');
    plot(axesHandles(4), status.time, vector(status, 'posHorizAccuracy'), ...
        'LineWidth', 1.2, 'DisplayName', 'Horizontal', ...
        'Tag', 'ekfHorizontalAccuracy');
    plot(axesHandles(4), status.time, vector(status, 'posVertAccuracy'), ...
        'LineWidth', 1.2, 'DisplayName', 'Vertical', ...
        'Tag', 'ekfVerticalAccuracy');
    title(axesHandles(4), 'Reported Position Accuracy');
    ylabel(axesHandles(4), 'Accuracy estimate (m)');
    legend(axesHandles(4), 'Location', 'best');

    axesHandles(5) = nexttile(layout); style(axesHandles(5), 'ekfResetAxes');
    hold(axesHandles(5), 'on');
    resetNames = {'resetCountVelocityNE', 'resetCountVelocityD', ...
        'resetCountPositionNE', 'resetCountPositionD', ...
        'resetCountQuaternion'};
    resetLabels = {'Vel NE', 'Vel D', 'Pos NE', 'Pos D', 'Quaternion'};
    for index = 1:numel(resetNames)
        stairs(axesHandles(5), status.time, vector(status, resetNames{index}), ...
            'LineWidth', 1.0, 'DisplayName', resetLabels{index}, ...
            'Tag', ['ekf' resetNames{index}]);
    end
    title(axesHandles(5), 'Cumulative Estimator Reset Counters');
    ylabel(axesHandles(5), 'Cumulative count');
    legend(axesHandles(5), 'Location', 'best');

    axesHandles(6) = nexttile(layout); style(axesHandles(6), 'ekfFlagAxes');
    hold(axesHandles(6), 'on');
    flagNames = {'filterFaultFlags', 'gpsCheckFailFlags', ...
        'healthFlags', 'timeoutFlags'};
    flagLabels = {'Filter fault bitmask', 'GPS check-fail bitmask', ...
        'Health bitmask', 'Timeout bitmask'};
    for index = 1:numel(flagNames)
        stairs(axesHandles(6), status.time, vector(status, flagNames{index}), ...
            'LineWidth', 1.0, 'DisplayName', flagLabels{index}, ...
            'Tag', ['ekf' flagNames{index}]);
    end
    title(axesHandles(6), 'Raw Estimator Status Bitmasks');
    ylabel(axesHandles(6), 'Raw integer value');
    legend(axesHandles(6), 'Location', 'best');

    finish(axesHandles, flightData);
    attachFigureProvenance(figureHandle, { ...
        'Summary test ratios', 'estimator_status', ...
        'vel/pos/hgt/hdg_test_ratio', status.instanceID, 'ratio', ...
        'none; reference line at 1', 'Direct', ...
        'Fields mapped by name; official normalized gate convention'; ...
        'Position innovations', 'estimator_innovations', ...
        'gps_hpos, gps_vpos, baro_vpos', innovations.instanceID, 'm', ...
        'vector columns plotted separately', 'Direct', ...
        'Field dimensions and topic time checked'; ...
        'Velocity innovations', 'estimator_innovations', ...
        'gps_hvel, gps_vvel', innovations.instanceID, 'm/s', ...
        'vector columns plotted separately', 'Direct', ...
        'Field dimensions and topic time checked'; ...
        'Position accuracy', 'estimator_status', ...
        'pos_horiz_accuracy, pos_vert_accuracy', status.instanceID, 'm', ...
        'none', 'Direct', 'Field names and units mapped'; ...
        'Reset counters', 'estimator_status', 'reset_count_*', ...
        status.instanceID, 'count', 'none', 'Direct', ...
        'Displayed as cumulative logged counters'; ...
        'Status flags', 'estimator_status', ...
        'filter_fault_flags, gps_check_fail_flags, health_flags, timeout_flags', ...
        status.instanceID, 'bitmask', 'none', 'Direct', ...
        'Raw values only; no unverified bit decoding'});

end

function plotInnovationGroup(ax, signal, names, labels, heading, unit, tag)
    hold(ax, 'on'); count = 0;
    for fieldIndex = 1:numel(names)
        matrix = matrixField(signal, names{fieldIndex});
        for column = 1:size(matrix, 2)
            count = count + 1;
            label = labels{fieldIndex};
            if size(matrix, 2) > 1
                label = sprintf('%s %d', label, column);
            end
            plot(ax, signal.time, matrix(:, column), 'LineWidth', 1.0, ...
                'DisplayName', label, 'Tag', sprintf('%s%d', tag, count));
        end
    end
    title(ax, heading); ylabel(ax, unit);
    if count > 0, legend(ax, 'Location', 'best'); end
end

function signal = signalOrEmpty(data, name)
    signal = struct('available', false, 'time', zeros(0, 1), ...
        'instanceID', NaN);
    if isfield(data, name), signal = data.(name); end
end

function value = vector(signal, name)
    value = nan(numel(signal.time), 1);
    if isfield(signal, name) && numel(signal.(name)) == numel(signal.time)
        value = double(signal.(name)(:));
    end
end

function value = matrixField(signal, name)
    value = nan(numel(signal.time), 0);
    if isfield(signal, name) && size(signal.(name), 1) == numel(signal.time)
        value = double(signal.(name));
    end
end

function result = available(data, name)
    result = isfield(data, name) && isfield(data.(name), 'available') && ...
        data.(name).available;
end

function style(ax, tag)
    set(ax, 'Tag', tag, 'Color', 'white', ...
        'XColor', [0.15 0.15 0.15], 'YColor', [0.15 0.15 0.15], ...
        'GridColor', [0.70 0.70 0.70], 'GridAlpha', 0.4);
    hold(ax, 'on'); grid(ax, 'on'); box(ax, 'on');
end

function finish(axesHandles, flightData)
    for index = 1:numel(axesHandles)
        xlabel(axesHandles(index), 'Time from log start (s)');
    end
    linkaxes(axesHandles, 'x'); setFullTimeLimits(axesHandles(1), flightData);
    decorateFlightTimeAxes(axesHandles, flightData);
    for index = 1:numel(axesHandles), axesHandles(index).Title.Color = [0.10 0.10 0.10]; end
end

function setFullTimeLimits(ax, data)
    if isfield(data, 'metadata') && isfield(data.metadata, 'duration') && ...
            isfinite(data.metadata.duration) && data.metadata.duration > 0
        xlim(ax, [0 data.metadata.duration]);
    end
end

function unavailable(fig, message)
    ax = axes(fig); axis(ax, 'off'); text(ax, 0.5, 0.5, message, ...
        'HorizontalAlignment', 'center', 'Interpreter', 'none', 'FontSize', 12);
end
