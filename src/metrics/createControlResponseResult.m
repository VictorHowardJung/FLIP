function row = createControlResponseResult(settlingThreshold, tailFraction)
% Create a response record with independent measurement and validity fields.
    row = struct('StepTime', NaN, 'ResponseStart', NaN, 'WindowStart', NaN, 'WindowEnd', NaN, ...
        'InitialValue', NaN, 'InitialTarget', NaN, 'Target', NaN, 'CommandStep', NaN, ...
        'RiseTime', NaN, 'RiseStart', NaN, 'RiseEnd', NaN, 'SettlingTime', NaN, ...
        'Overshoot', NaN, 'PeakTime', NaN, 'PeakAt', NaN, 'PeakValue', NaN, ...
        'SteadyStateValue', NaN, 'SteadyStateError', NaN, 'TailMeanError', NaN, ...
        'TailStart', NaN, 'SettlingBand', NaN, 'StepDetected', false, 'Settled', false, ...
        'SteadyStateAvailable', false, 'FinalValueStable', false, 'ReferenceStable', false, ...
        'DataComplete', false, 'FinalValueEstimated', false, ...
        'SettlingBandPercent', 100 * settlingThreshold, 'TailFraction', tailFraction, ...
        'AnalysisMode', "Detected step", 'Status', "");
end
