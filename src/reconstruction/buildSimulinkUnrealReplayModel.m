function modelPath = buildSimulinkUnrealReplayModel(options)
% Build a FLIP Unreal replay model using UAV Toolbox Simulation 3D blocks.

    arguments

        options.OutputFile (1, 1) string = ""
        options.Scene (1, 1) string = "Airport"
        options.OpenModel (1, 1) logical = false
        options.EmbeddedCamera (1, 1) logical = false
        options.GraphicsQuality (1, 1) string {mustBeMember(options.GraphicsQuality, ...
            ["low", "medium", "high", "epic", "cinematic"])} = "epic"

    end

    validateSimulinkEnvironment();
    validScenes = [ ...
        "Airport", "Blank scene", "Curved road", ...
        "Double lane change", "Earth", "Empty Grass", "Empty scene", ...
        "Large parking lot", "Moon", "Open surface", "Space", ...
        "Straight road", "US city block", "Underwater"];

    if ~any(options.Scene == validScenes)

        error('FLIP:InvalidSimulinkUnrealScene', ...
            'The requested scene is not available in UAV Toolbox R2026a.');

    end

    projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));

    if strlength(options.OutputFile) == 0

        modelDirectory = fullfile(projectRoot, 'models');
        modelPath = fullfile(modelDirectory, 'FLIP_UnrealReplay.slx');

    else

        modelPath = char(options.OutputFile);
        modelDirectory = fileparts(modelPath);

    end

    if ~isfolder(modelDirectory)

        mkdir(modelDirectory);

    end

    [~, modelName, extension] = fileparts(modelPath);

    if ~strcmpi(extension, '.slx')

        error('FLIP:InvalidSimulinkModelExtension', ...
            'The Unreal replay model output must use the .slx extension.');

    end

    if bdIsLoaded(modelName)

        close_system(modelName, 0);

    end

    load_system('simulink');
    load_system('uavsim3dlib');
    load_system('sim3dlib');
    new_system(modelName);
    cleanup = onCleanup(@() closeModelIfLoaded(modelName));

    set_param(modelName, ...
        'SolverType', 'Fixed-step', ...
        'Solver', 'FixedStepDiscrete', ...
        'FixedStep', 'flipSimulinkSampleTime', ...
        'StartTime', 'flipSimulinkStartTime', ...
        'StopTime', 'flipSimulinkStopTime', ...
        'EnablePacing', 'on', ...
        'PacingRate', '1', ...
        'ReturnWorkspaceOutputs', 'on');

    rendering = add_block('sim3dlib/Simulation 3D Actor', ...
        modelName + "/Rendering Quality", ...
        'ActorName', 'FLIPRenderingSettings', 'Operation', 'Create at setup', ...
        'SourceFile', '', ...
        'InitScriptText', sprintf('configureReplayRendering(World, "%s");', ...
            options.GraphicsQuality), ...
        'SampleTime', 'flipSimulinkSampleTime', ...
        'Priority', '-3', 'Position', [620 25 850 65]);
    renderingPorts = get_param(rendering, 'PortHandles');
    for portIndex = 1:numel(renderingPorts.Outport)
        terminator = add_block('simulink/Sinks/Terminator', ...
            modelName + "/Rendering Status " + portIndex, ...
            'Position', [900 25 + 25*portIndex 920 45 + 25*portIndex]);
        add_line(modelName, renderingPorts.Outport(portIndex), ...
            inputPort(terminator, 1));
    end

    translationSource = add_block( ...
        'simulink/Sources/From Workspace', ...
        modelName + "/Log Translation World XYZ", ...
        'VariableName', 'flipSimulinkTranslation', ...
        'SampleTime', 'flipSimulinkSampleTime', ...
        'Interpolate', 'off', ...
        'OutputAfterFinalValue', 'Holding final value', ...
        'Position', [40 80 200 110]);
    rotationSource = add_block( ...
        'simulink/Sources/From Workspace', ...
        modelName + "/Log Rotation YPR", ...
        'VariableName', 'flipSimulinkRotationYPR', ...
        'SampleTime', 'flipSimulinkSampleTime', ...
        'Interpolate', 'off', ...
        'OutputAfterFinalValue', 'Holding final value', ...
        'Position', [40 150 200 180]);
    speedSource = add_block( ...
        'simulink/Sources/From Workspace', ...
        modelName + "/Logged Speed", ...
        'VariableName', 'flipSimulinkSpeed', ...
        'SampleTime', 'flipSimulinkSampleTime', ...
        'Interpolate', 'off', ...
        'OutputAfterFinalValue', 'Holding final value', ...
        'Position', [40 260 200 290]);
    altitudeSource = add_block( ...
        'simulink/Sources/From Workspace', ...
        modelName + "/Altitude AGL", ...
        'VariableName', 'flipSimulinkAltitude', ...
        'SampleTime', 'flipSimulinkSampleTime', ...
        'Interpolate', 'off', ...
        'OutputAfterFinalValue', 'Holding final value', ...
        'Position', [40 330 200 360]);
    partTranslationSource = add_block( ...
        'simulink/Sources/From Workspace', ...
        modelName + "/Quadrotor Part Translation", ...
        'VariableName', 'flipSimulinkActorTranslation', ...
        'SampleTime', 'flipSimulinkSampleTime', ...
        'Interpolate', 'off', ...
        'OutputAfterFinalValue', 'Holding final value', ...
        'Position', [40 525 220 555]);
    partRotationSource = add_block( ...
        'simulink/Sources/From Workspace', ...
        modelName + "/Quadrotor Part Rotation", ...
        'VariableName', 'flipSimulinkActorRotation', ...
        'SampleTime', 'flipSimulinkSampleTime', ...
        'Interpolate', 'off', ...
        'OutputAfterFinalValue', 'Holding final value', ...
        'Position', [40 575 220 605]);
    partScaleSource = add_block( ...
        'simulink/Sources/From Workspace', ...
        modelName + "/Quadrotor Part Scale", ...
        'VariableName', 'flipSimulinkActorScale', ...
        'SampleTime', 'flipSimulinkSampleTime', ...
        'Interpolate', 'off', ...
        'OutputAfterFinalValue', 'Holding final value', ...
        'Position', [40 625 220 655]);

    vehicle = add_block( ...
        'uavsim3dlib/Simulation 3D UAV Vehicle', ...
        modelName + "/Simulation 3D UAV Vehicle", ...
        'Mesh', 'Quadrotor', ...
        'Color', 'Orange', ...
        'ActorName', 'FLIPVehicle', ...
        'UseGlobalFrame', 'off', ...
        'InitialTranslation', 'flipSimulinkInitialTranslation', ...
        'InitialRotation', 'flipSimulinkInitialRotationYPR', ...
        'SampleTime', 'flipSimulinkSampleTime', ...
        'Priority', '-1', ...
        'Position', [300 95 500 185]);
    scene = add_block( ...
        'uavsim3dlib/Simulation 3D Scene Configuration', ...
        modelName + "/Simulation 3D Scene Configuration", ...
        'SceneDesc', char(options.Scene), ...
        'vehTag', 'Custom', ...
        'ViewpointName', 'FLIP Operator View', ...
        'FreeCameraInitialTranslation', ...
        'flipSimulinkOperatorViewTranslation', ...
        'FreeCameraInitialRotation', ...
        'flipSimulinkOperatorViewRotation', ...
        'Ts', 'flipSimulinkSampleTime', ...
        'EnableWindow', 'on', ...
        'EnableAnimationRecording', 'off', ...
        'Priority', '0', ...
        'Position', [620 95 850 185]);
    partTransform = add_block( ...
        'sim3dlib/Simulation 3D Actor Transform Set', ...
        modelName + "/Logged Propeller Transform", ...
        'ActorTag', 'FLIPVehicle', ...
        'NumberOfParts', '17', ...
        'CustNumOfParts', '17', ...
        'Translation', 'zeros(17, 3)', ...
        'Rotation', 'zeros(17, 3)', ...
        'Scale', 'ones(17, 3)', ...
        'Ts', 'flipSimulinkSampleTime', ...
        'Priority', '1', ...
        'Position', [330 520 555 660]);

    speedScope = add_block( ...
        'simulink/Sinks/Scope', modelName + "/Speed Scope", ...
        'Position', [315 245 420 305]);
    speedDisplay = add_block( ...
        'simulink/Sinks/Display', modelName + "/Speed mps", ...
        'Position', [500 250 590 290]);
    altitudeScope = add_block( ...
        'simulink/Sinks/Scope', modelName + "/Altitude AGL Scope", ...
        'Position', [315 320 420 380]);
    altitudeDisplay = add_block( ...
        'simulink/Sinks/Display', modelName + "/Altitude AGL m", ...
        'Position', [500 330 590 370]);
    attitudeScope = add_block( ...
        'simulink/Sinks/Scope', modelName + "/Attitude YPR Scope", ...
        'Position', [315 415 420 475]);
    clock = add_block( ...
        'simulink/Sources/Clock', modelName + "/ULog Relative Time", ...
        'Position', [45 450 75 470]);
    timeDisplay = add_block( ...
        'simulink/Sinks/Display', modelName + "/Time seconds", ...
        'Position', [130 435 220 475]);

    add_line(modelName, outputPort(translationSource, 1), ...
        inputPort(vehicle, 1), 'autorouting', 'on');
    add_line(modelName, outputPort(rotationSource, 1), ...
        inputPort(vehicle, 2), 'autorouting', 'on');
    add_line(modelName, outputPort(speedSource, 1), ...
        inputPort(speedScope, 1), 'autorouting', 'on');
    add_line(modelName, outputPort(speedSource, 1), ...
        inputPort(speedDisplay, 1), 'autorouting', 'on');
    add_line(modelName, outputPort(altitudeSource, 1), ...
        inputPort(altitudeScope, 1), 'autorouting', 'on');
    add_line(modelName, outputPort(altitudeSource, 1), ...
        inputPort(altitudeDisplay, 1), 'autorouting', 'on');
    add_line(modelName, outputPort(rotationSource, 1), ...
        inputPort(attitudeScope, 1), 'autorouting', 'on');
    add_line(modelName, outputPort(clock, 1), ...
        inputPort(timeDisplay, 1), 'autorouting', 'on');
    add_line(modelName, outputPort(partTranslationSource, 1), ...
        inputPort(partTransform, 1), 'autorouting', 'on');
    add_line(modelName, outputPort(partRotationSource, 1), ...
        inputPort(partTransform, 2), 'autorouting', 'on');
    add_line(modelName, outputPort(partScaleSource, 1), ...
        inputPort(partTransform, 3), 'autorouting', 'on');

    Simulink.Annotation(modelName, sprintf([ ...
        'FLIP log-derived reconstruction\n' ...
        'Presentation: fixed operator FRU [Forward Right Up] m\n' ...
        'Rendering: fixed quality profile set during scene initialization\n' ...
        'Translation: Unreal ISO world [Forward -Right Up] m\n' ...
        'Ground: first valid position, altitude constrained to >= 0 m\n' ...
        'Rotation: [-yaw_view -pitch_FRD roll_FRD] rad\n' ...
        'Camera: fixed operator viewpoint; it does not follow the UAV\n' ...
        'Presentation: trajectory-centered operator framing\n' ...
        'Airport placement: vehicle and camera use runtime X=5000 m offset\n' ...
        'Timing: up to 60 fps, paced 1:1 with wall-clock time\n' ...
        'Propellers: motor-command speed; freeze at logged disarm\n' ...
        'Scene is illustrative and is not flight-site evidence.']));

    if options.EmbeddedCamera
        sourceBlocks = [translationSource, rotationSource, speedSource, ...
            altitudeSource, partTranslationSource, partRotationSource, partScaleSource];
        destinations = cell(1, numel(sourceBlocks));
        for index = 1:numel(sourceBlocks)
            ports = get_param(sourceBlocks(index), 'PortHandles');
            line = get_param(ports.Outport(1), 'Line');
            destinations{index} = get_param(line, 'DstPortHandle');
            delete_line(line);
            delete_block(sourceBlocks(index));
        end
        poseSource = add_block( ...
            'simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
            modelName + "/Replay Frame Source", ...
            'FunctionName', 'flipReplayPoseSource', ...
            'Parameters', '1/30', ...
            'Priority', '-2', 'Position', [40 70 220 400]);
        for index = 1:numel(destinations)
            for destination = reshape(destinations{index}, 1, [])
                add_line(modelName, outputPort(poseSource, index), destination, ...
                    'autorouting', 'on');
            end
        end
        set_param(scene, 'EnableWindow', 'off');
        camera = add_block('uavsim3dlib/Simulation 3D Camera', ...
            modelName + "/Replay Camera", ...
            'sensorId', '1', 'sensorName', 'FLIPReplayCamera', ...
            'vehTag', 'Scene Origin', 'CoordinateSystem', 'ISO8855', ...
            'tmountOffset', 'flipSimulinkOperatorViewTranslation', ...
            'rmountOffset', 'flipSimulinkOperatorViewRotation .* [1 -1 1]', ...
            'ImageSize', '[1080 1920]', 'FocalLength', '[960 960]', ...
            'OpticalCenter', '[960 540]', ...
            'SampleTime', 'flipSimulinkSampleTime', ...
            'Priority', '2', 'Position', [620 520 820 570]);
        sink = add_block( ...
            'simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
            modelName + "/Synchronized Frame Sink", ...
            'FunctionName', 'flipReplayFrameSink', ...
            'Position', [900 520 1090 570]);
        add_line(modelName, outputPort(camera, 1), inputPort(sink, 1));
        add_line(modelName, outputPort(poseSource, 8), inputPort(sink, 2));
        delete_line(get_param(inputPort(timeDisplay, 1), 'Line'));
        add_line(modelName, outputPort(poseSource, 8), inputPort(timeDisplay, 1));
    end

    set_param(scene, 'vehTag', 'Custom', ...
        'ViewpointName', 'FLIP Operator View', ...
        'FreeCameraInitialTranslation', 'flipSimulinkOperatorViewTranslation', ...
        'FreeCameraInitialRotation', 'flipSimulinkOperatorViewRotation');
    set_param(modelName, 'Location', [100 100 1000 750]);
    assert(strcmp(get_param(scene, 'vehTag'), 'Custom'), ...
        'FLIP:OperatorViewConfigurationFailed', ...
        'The operator camera viewpoint could not be configured.');
    save_system(modelName, modelPath);

    clear cleanup;

    if options.OpenModel

        load_system(modelPath);
        open_system(modelName);

    end

end


function portHandle = outputPort(block, index)

    portHandles = get_param(block, 'PortHandles');
    portHandle = portHandles.Outport(index);

end


function portHandle = inputPort(block, index)

    portHandles = get_param(block, 'PortHandles');
    portHandle = portHandles.Inport(index);

end


function validateSimulinkEnvironment()

    if isempty(ver('simulink')) || ~license('test', 'Simulink')

        error('FLIP:MissingSimulink', ...
            'The UAV replay model requires Simulink.');

    end

    if isempty(ver('uav')) || ~license('test', 'UAV_Toolbox')

        error('FLIP:MissingUAVToolbox', ...
            'The UAV replay model requires UAV Toolbox.');

    end

    if isempty(ver('sl3d')) || ...
            ~license('test', 'Virtual_Reality_Toolbox')

        error('FLIP:MissingSimulink3DAnimation', ...
            'The UAV replay model requires Simulink 3D Animation.');

    end

end


function closeModelIfLoaded(modelName)

    if bdIsLoaded(modelName)

        close_system(modelName, 0);

    end

end
