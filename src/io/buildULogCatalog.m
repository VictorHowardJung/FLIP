function catalog = buildULogCatalog(ulog)
% Catalog ULog topics, instances, and FLIP support in a MATLAB table.

    availableTopics = ulog.AvailableTopics;

    topicName = string(availableTopics.TopicNames);
    instanceID = double(availableTopics.InstanceID);
    startTime = seconds(availableTopics.StartTimestamp);
    endTime = seconds(availableTopics.LastTimestamp);
    sampleCount = double(availableTopics.NumMessages);

    supportedTopics = [ ...
        "vehicle_local_position" ...
        "vehicle_local_position_setpoint" ...
        "trajectory_setpoint" ...
        "vehicle_attitude" ...
        "vehicle_attitude_setpoint" ...
        "vehicle_angular_velocity" ...
        "vehicle_rates_setpoint" ...
        "vehicle_status" ...
        "actuator_armed" ...
        "vehicle_land_detected" ...
        "failure_detector_status" ...
        "actuator_motors" ...
        "actuator_outputs" ...
        "battery_status" ...
        "estimator_selector_status" ...
        "vehicle_imu_status" ...
        "sensors_status_imu" ...
        "estimator_status" ...
        "estimator_innovations" ...
        "estimator_innovation_test_ratios" ...
        "vehicle_gps_position" ...
        "vehicle_thrust_setpoint" ...
        "vehicle_torque_setpoint" ...
        "manual_control_setpoint" ...
        "input_rc" ...
        "cpuload" ...
        "radio_status" ...
        "telemetry_status" ...
        "system_power"];

    supported = ismember(topicName, supportedTopics);
    category = strings(size(topicName));
    category(:) = "not_yet_supported";

    actualTopics = [ ...
        "vehicle_local_position" ...
        "vehicle_attitude" ...
        "vehicle_angular_velocity"];

    setpointTopics = [ ...
        "vehicle_local_position_setpoint" ...
        "trajectory_setpoint" ...
        "vehicle_attitude_setpoint" ...
        "vehicle_rates_setpoint"];

    category(ismember(topicName, actualTopics)) = "actual_state";
    category(ismember(topicName, setpointTopics)) = "setpoint";

    stateTopics = [ ...
        "vehicle_status" ...
        "actuator_armed" ...
        "vehicle_land_detected"];
    safetyTopics = "failure_detector_status";

    category(ismember(topicName, stateTopics)) = "flight_state";
    category(ismember(topicName, safetyTopics)) = "safety_state";

    controlOutputTopics = ["actuator_motors" "actuator_outputs"];
    category(ismember(topicName, controlOutputTopics)) = "control_output";

    category(topicName == "battery_status") = "energy_system";

    imuTopics = ["vehicle_imu_status" "sensors_status_imu"];
    estimatorTopics = [ ...
        "estimator_selector_status" "estimator_status" ...
        "estimator_innovations" "estimator_innovation_test_ratios"];
    navigationTopics = "vehicle_gps_position";
    commandTopics = [ ...
        "vehicle_thrust_setpoint" "vehicle_torque_setpoint" ...
        "manual_control_setpoint" "input_rc"];
    systemTopics = [ ...
        "cpuload" "radio_status" "telemetry_status" "system_power"];
    category(ismember(topicName, imuTopics)) = "imu_diagnostics";
    category(ismember(topicName, estimatorTopics)) = ...
        "estimator_diagnostics";
    category(ismember(topicName, navigationTopics)) = ...
        "navigation_diagnostics";
    category(ismember(topicName, commandTopics)) = "command_input";
    category(ismember(topicName, systemTopics)) = "system_diagnostics";

    catalog = table(topicName, instanceID, startTime, endTime, ...
        sampleCount, supported, category, ...
        'VariableNames', {'TopicName', 'InstanceID', 'StartTime', ...
        'EndTime', 'SampleCount', 'Supported', 'Category'});

end
